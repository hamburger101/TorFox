"""Compile the built UI (ui/dist) into a C++ resource table.

Usage: python -I scripts/gen_resources.py <dist_dir> <output.cc>

Only files with an allowlisted extension and a plain name are accepted; any
other file fails the build, so nothing unexpected can end up being served on
torfox://.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

# Bare MIME types: CEF passes them to Chromium verbatim, and a parameter such
# as "; charset=utf-8" would make the type unrecognisable. The handler sets
# the charset separately for text resources.
MIME = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".woff2": "font/woff2",
}
NAME_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
MAX_TOTAL = 8 * 1024 * 1024


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    dist = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2])
    if not (dist / "pages").is_dir():
        print(f"ERROR: {dist} has no pages/ directory; build the UI first", file=sys.stderr)
        return 1

    files = []
    total = 0
    for path in sorted(p for p in dist.rglob("*") if p.is_file()):
        rel = path.relative_to(dist).as_posix()
        parts = rel.split("/")
        if any(not NAME_RE.match(part) or part.startswith(".") for part in parts):
            print(f"ERROR: unexpected file name in UI bundle: {rel}", file=sys.stderr)
            return 1
        if not (rel.startswith("assets/") and len(parts) == 2) and not (
            len(parts) == 3 and parts[0] == "pages" and parts[2] == "index.html"
        ):
            print(f"ERROR: unexpected file location in UI bundle: {rel}", file=sys.stderr)
            return 1
        mime = MIME.get(path.suffix.lower())
        if mime is None:
            print(f"ERROR: file type not allowed in UI bundle: {rel}", file=sys.stderr)
            return 1
        data = path.read_bytes()
        total += len(data)
        files.append((rel, mime, data))
    if total > MAX_TOTAL:
        print(f"ERROR: UI bundle is {total} bytes, over the {MAX_TOTAL} limit", file=sys.stderr)
        return 1

    lines = [
        "// Generated by scripts/gen_resources.py. Do not edit.",
        '#include "src/browser/scheme/resources.h"',
        "",
        "namespace torfox::resources {",
        "namespace {",
    ]
    for i, (_, _, data) in enumerate(files):
        lines.append(f"const unsigned char kData{i}[] = {{")
        for start in range(0, len(data), 24):
            chunk = data[start : start + 24]
            lines.append("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
        if not data:
            lines.append("  0x00,")
        lines.append("};")
    lines.append("const Resource kResources[] = {")
    for i, (rel, mime, data) in enumerate(files):
        lines.append(f'  {{"{rel}", "{mime}", kData{i}, {len(data)}u}},')
    lines += [
        "};",
        "}  // namespace",
        "",
        "const Resource* Find(std::string_view path) {",
        "  for (const Resource& r : kResources) {",
        "    if (r.path == path) {",
        "      return &r;",
        "    }",
        "  }",
        "  return nullptr;",
        "}",
        "",
        "std::size_t Count() {",
        f"  return {len(files)}u;",
        "}",
        "",
        "}  // namespace torfox::resources",
        "",
    ]
    text = "\n".join(lines)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8", newline="\n")
    print(f"Embedded {len(files)} UI files ({total} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
