"""Generate the compiled-in tracker domain table.

Reads third_party/easyprivacy/domains.txt (made by update_trackers.py),
refuses to continue if its SHA-256 differs from sources.lock.json, and writes
a C++ include with the domains sorted in byte order.

Usage:  python gen_trackers.py <out.inc>
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "third_party" / "easyprivacy"
DOMAIN = re.compile(r"[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    lock = json.loads((SRC / "sources.lock.json").read_text(encoding="utf-8"))
    data = (SRC / "domains.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != lock["domains_sha256"]:
        raise SystemExit("gen_trackers: domains.txt does not match sources.lock.json; refusing to build")
    domains = data.decode("ascii").split("\n")
    if domains[-1] != "":
        raise SystemExit("gen_trackers: domains.txt must end with a newline")
    domains = domains[:-1]
    for d in domains:
        if not DOMAIN.fullmatch(d):
            raise SystemExit(f"gen_trackers: not a domain: {d!r}")
    if domains != sorted(set(domains)) or len(domains) != lock["domains"]:
        raise SystemExit("gen_trackers: domains.txt must be sorted, unique and complete")
    body = ",\n".join(f'    "{d}"' for d in domains)
    Path(argv[1]).write_bytes((
        "// Generated by scripts/gen_trackers.py from third_party/easyprivacy. Do not edit.\n"
        f"// EasyPrivacy ({lock['source']}) commit {lock['commit']}.\n"
        f'inline constexpr std::string_view kTrackerListCommit = "{lock["commit"]}";\n'
        f"inline constexpr std::string_view kTrackerDomains[] = {{\n{body},\n}};\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
