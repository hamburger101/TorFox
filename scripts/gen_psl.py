"""Generate the compiled-in Public Suffix List tables.

Reads the vendored list (third_party/publicsuffix), refuses to continue if
its SHA-256 differs from SOURCE.json, and writes a C++ include with sorted
rule tables in ASCII (punycode) form plus the set of top-level domains in
both Unicode and ASCII form. With --tests, also writes the official test
vectors (test_psl.txt) converted to ASCII.

Usage:  python gen_psl.py <out.inc> [--tests <tests.inc>]
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "third_party" / "publicsuffix"


def checked(name: str) -> bytes:
    source = json.loads((SRC / "SOURCE.json").read_text(encoding="utf-8"))
    data = (SRC / name).read_bytes()
    want = source["files"][name]["sha256"]
    if hashlib.sha256(data).hexdigest() != want:
        raise SystemExit(f"gen_psl: {name} does not match SOURCE.json; refusing to build")
    return data


def to_ascii(host: str) -> str:
    labels = []
    for label in host.lower().split("."):
        if label and not label.isascii():
            label = "xn--" + label.encode("punycode").decode("ascii")
        labels.append(label)
    return ".".join(labels)


def cxx(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C, 0x3F):
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    # Separate hex escapes from following hex digits.
    return '"' + '""'.join(re.split(r"(?<=\\x[0-9a-f]{2})(?=[0-9a-fA-F])", "".join(out))) + '"'


def array(name: str, items: list[str]) -> str:
    body = ",\n".join("    " + cxx(i) for i in items)
    return f"inline constexpr std::string_view {name}[] = {{\n{body},\n}};\n"


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 4) or (len(argv) == 4 and argv[2] != "--tests"):
        print(__doc__, file=sys.stderr)
        return 2
    source = json.loads((SRC / "SOURCE.json").read_text(encoding="utf-8"))
    text = checked("public_suffix_list.dat").decode("utf-8")
    rules: set[str] = set()
    private: set[str] = set()
    exceptions: set[str] = set()
    tlds: set[str] = set()
    section = None
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("// ===BEGIN ICANN DOMAINS==="):
            section = "icann"
        elif line.startswith("// ===BEGIN PRIVATE DOMAINS==="):
            section = "private"
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0]
        if section is None:
            raise SystemExit("gen_psl: rule outside a section")
        if rule.startswith("!"):
            exceptions.add(to_ascii(rule[1:]))
            continue
        ascii_rule = to_ascii(rule)
        (private if section == "private" else rules).add(ascii_rule)
        if section == "icann":
            tld = rule.lower().split(".")[-1]
            tlds.add(tld)
            tlds.add(to_ascii(tld))
    key = lambda s: s.encode("utf-8")  # noqa: E731  (byte order, as std::string_view compares)
    out = [
        "// Generated by scripts/gen_psl.py from third_party/publicsuffix. Do not edit.\n",
        f"// Public Suffix List commit {source['commit']} ({source['date']}).\n",
        f'inline constexpr std::string_view kPslCommit = "{source["commit"]}";\n',
        array("kPslIcannRules", sorted(rules, key=key)),
        array("kPslPrivateRules", sorted(private, key=key)),
        array("kPslExceptions", sorted(exceptions, key=key)),
        array("kPslTlds", sorted(tlds, key=key)),
    ]
    Path(argv[1]).write_bytes("".join(out).encode("utf-8"))

    if len(argv) == 4:
        vectors = []
        pattern = re.compile(r"^checkPublicSuffix\((null|'[^']*'), (null|'[^']*')\);")
        for line in checked("test_psl.txt").decode("utf-8").splitlines():
            m = pattern.match(line.strip())
            if not m:
                continue
            host, want = (None if g == "null" else g[1:-1] for g in m.groups())
            if host is None:
                continue
            vectors.append("    {%s, %s}," % (cxx(to_ascii(host)), "std::nullopt" if want is None else cxx(to_ascii(want))))
        if len(vectors) < 70:
            raise SystemExit("gen_psl: expected the official test vectors")
        body = "\n".join(vectors)
        Path(argv[3]).write_bytes((
            "// Generated by scripts/gen_psl.py from third_party/publicsuffix/test_psl.txt.\n"
            "struct PslVector { std::string_view host; std::optional<std::string_view> want; };\n"
            f"inline const PslVector kPslVectors[] = {{\n{body}\n}};\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
