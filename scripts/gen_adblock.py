"""Generate the compiled-in ad-blocking rules.

Reads third_party/easylist/filters.txt (made by update_adblock.py), refuses
to continue if its SHA-256 differs from sources.lock.json, and writes a C++
include with one string per rule. The rules are parsed when TorFox starts
(src/core/adblock); nothing is interpreted here.

Usage:  python gen_adblock.py <out.inc>
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "third_party" / "easylist"
# MSVC's limit for one string literal is 16380 bytes.
MAX_RULE = 8192


def literal(rule: bytes) -> str:
    out = []
    after_octal = False
    for b in rule:
        c = chr(b)
        if after_octal and c.isdigit():
            out.append('" "')  # A digit right after an octal escape starts a new literal.
        after_octal = False
        if c in '"\\?':  # "?" could start a trigraph in older compilers.
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
            after_octal = True
    return '"' + "".join(out) + '"'


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    lock = json.loads((SRC / "sources.lock.json").read_text(encoding="utf-8"))
    data = (SRC / "filters.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != lock["filters_sha256"]:
        raise SystemExit("gen_adblock: filters.txt does not match sources.lock.json; refusing to build")
    data.decode("utf-8")  # Must be UTF-8.
    rules = data.split(b"\n")
    if rules[-1] != b"":
        raise SystemExit("gen_adblock: filters.txt must end with a newline")
    rules = rules[:-1]
    if len(rules) != lock["filters"] or rules != sorted(set(rules)):
        raise SystemExit("gen_adblock: filters.txt must be sorted, unique and complete")
    for r in rules:
        if not r or len(r) > MAX_RULE or b"\r" in r:
            raise SystemExit(f"gen_adblock: bad rule {r[:80]!r}")
    body = ",\n".join(f"    {literal(r)}" for r in rules)
    Path(argv[1]).write_bytes((
        "// Generated by scripts/gen_adblock.py from third_party/easylist. Do not edit.\n"
        f"// EasyList ({lock['source']}) commit {lock['commit']}.\n"
        f'inline constexpr std::string_view kEasyListCommit = "{lock["commit"]}";\n'
        f"inline constexpr std::string_view kEasyListRules[] = {{\n{body},\n}};\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
